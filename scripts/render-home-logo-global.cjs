// 한국어 외 지역용 로고: 기존 피그마 로고의 TWINPOP 글자·느낌표 벡터를 재사용해 "TWIN / POP!" 두 줄로 배치.
// TWIN은 '트윈팝' 코랄 배색, POP!는 민트 배색. 실행: node scripts/render-home-logo-global.cjs
const fs=require('fs');
const src=fs.readFileSync('src/art/homeLogo.ts','utf8');
const svg=JSON.parse(src.match(/homeLogoSvg = (".*?");/s)[1]);
const L=svg.split('\n');
const defs=L.slice(L.indexOf('<defs>'),L.indexOf('</defs>')+1).join('\n');
// 각 글자: use(외곽) + mask(4줄) + 테두리 path + 하이라이트 path = 7줄. 시작 줄 번호(원본 SVG 기준)
const letter=start=>L.slice(start,start+7).join('\n');
const LETTERS={T:59,W:45,I:52,N:38,P1:31,O:17,P2:24};
const BANG=L.slice(1,5).join('\n');
const mintToCoral=s=>s.replace(/#ACD8BE/g,'#FFA08E').replace(/#86B495/g,'#ED8678').replace(/#DDEECF/g,'#FFD4CC');
const coralToMint=s=>s.replace(/#ED8678/g,'#86B495').replace(/#FFD4CC/g,'#DDEECF').replace(/#FFA08E/g,'#ACD8BE');
// 원본 좌표 → 새 배치(이동량). TWIN 원본 x15~136,y81~132 / POP x136~224,y71~116 / ! x203~215,y12~66
const line1=`<g transform="translate(-10 -78)">${mintToCoral(['T','W','I','N'].map(k=>letter(LETTERS[k])).join('\n'))}</g>`;
const line2=`<g transform="translate(-114 -23)">${['P1','O','P2'].map(k=>letter(LETTERS[k])).join('\n')}</g>`;
const bang=`<g transform="translate(-56 38) scale(.82)">${coralToMint(BANG)}</g>`;
const out=`<svg viewBox="0 0 136 103" fill="none" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">\n${line1}\n${line2}\n${bang}\n${defs}\n</svg>`;
fs.writeFileSync('src/art/homeLogoGlobal.ts','// TWIN / POP! 로고(한국어 외 지역). Generated by scripts/render-home-logo-global.cjs from homeLogo.ts.\nexport const homeLogoGlobalSvg = '+JSON.stringify(out)+';\nexport const homeLogoGlobalAspect = '+(136/103)+';\n');
if(process.argv[2]){const {Resvg}=require('@resvg/resvg-js');fs.writeFileSync(process.argv[2],new Resvg(out,{fitTo:{mode:'width',value:544},background:'#fff8eb'}).render().asPng());}
