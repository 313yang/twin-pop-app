"""Embed the user-supplied Figma SVG without redrawing its paths or styling."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET
source = Path('assets/art/home-title.svg').read_text()
_, _, width, height = map(float, ET.fromstring(source).attrib['viewBox'].split())
# SvgXml supplies the responsive display size. Preserve the original viewBox,
# paths, masks, colors, highlights, opacity and drop-shadow shapes verbatim.
svg = re.sub(r'(<svg\b[^>]*?)\swidth="[^"]*"', r'\1', source, count=1)
svg = re.sub(r'(<svg\b[^>]*?)\sheight="[^"]*"', r'\1', svg, count=1)
Path('src/art/homeLogo.ts').write_text('// User-provided Figma artwork. Generated by scripts/render-home-logo.py.\nexport const homeLogoSvg = '+json.dumps(svg)+';\nexport const homeLogoAspect = '+str(width / height)+';\n')
