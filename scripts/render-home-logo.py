"""Build outlined KccSign logo paths; requires fontTools. No runtime font renderer."""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
import json
font=TTFont('assets/fonts/KccSign.otf');glyphs=font.getGlyphSet();cmap=font.getBestCmap()
def line(text,width,baseline,fill,stroke,shadow):
 advance=sum(glyphs[cmap[ord(c)]].width for c in text);scale=width/advance;x=0;parts=[]
 for c in text:
  glyph=glyphs[cmap[ord(c)]];pen=SVGPathPen(glyphs);glyph.draw(pen)
  if pen.getCommands():parts.append(f'<path d="{pen.getCommands()}" transform="translate({x} 0)"/>')
  x+=glyph.width
 paths=''.join(parts);left=(400-width)/2
 return f'<g transform="translate({left} {baseline+6}) scale({scale} {-scale})" fill="{shadow}">{paths}</g><g transform="translate({left} {baseline}) scale({scale} {-scale})" fill="{fill}" stroke="{stroke}" stroke-width="{2.8/scale}" stroke-linejoin="round" paint-order="stroke fill">{paths}</g>'
svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 230"><g transform="rotate(-7 200 115)">'+line('트윈팝!',335,115,'#ffa493','#d58e7b','#ffc7b5')+line('TWIN POP',325,194,'#b0d8bb','#80b393','#d3e6cb')+'<g fill="none" stroke="#fffaf1" stroke-width="3.2" stroke-linecap="round" opacity=".95"><path d="M49 62v5M201 64v8M344 105v5M73 173v7M286 157l-3 3"/></g></g></svg>'
Path('src/art/homeLogo.ts').write_text('// Generated by scripts/render-home-logo.py from the bundled KccSign font.\nexport const homeLogoSvg = '+json.dumps(svg)+';\n')
